    /*
    =========================================
    Get day of year
    =========================================
    */

    function getDayOfYear(date) {

        const start =
            new Date(
                date.getFullYear(),
                0,
                0
            );

        const difference =
            date - start;

        return Math.floor(
            difference /
            (1000 * 60 * 60 * 24)
        );

    }


    /*
    =========================================
    Get today's fact
    =========================================
    */

    function getTodayFact() {

        if (!FACTS.length) {

            return "";

        }

        const today =
            new Date();

        let day =
            getDayOfYear(today);

        /*
        =====================================
        PREVIA archive contains 365 facts.

        In leap years we skip February 29
        so the annual archive remains
        exactly 365 entries.
        =====================================
        */

        const isLeapYear =
            (
                today.getFullYear() % 4 === 0 &&
                today.getFullYear() % 100 !== 0
            ) ||
            (
                today.getFullYear() % 400 === 0
            );

        if (
            isLeapYear &&
            day > 59
        ) {

            day--;

        }

        /*
        =====================================
        If the archive contains fewer than
        365 entries, keep the index safe.
        =====================================
        */

        const index =
            (day - 1) %
            FACTS.length;

        return FACTS[index];

    }


